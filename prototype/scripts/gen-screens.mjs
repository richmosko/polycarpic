// Generates src/lib/screens/<name>.ts from docs/DESIGN/styled-screens/<name>.html.
// Re-run (`npm run gen`) when DESIGN changes. The markup is carried verbatim
// (comments stripped, .html links rewritten to routes); no palette value is added.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../docs/DESIGN/styled-screens');
const out = join(here, '../src/lib/screens');

const names = [];
for (const f of readdirSync(src).filter((f) => f.endsWith('.html'))) {
  const name = f.replace(/\.html$/, '');
  const raw = readFileSync(join(src, f), 'utf8');
  const bodyTag = raw.match(/<body([^>]*)>/);
  const bodyClass = (bodyTag[1].match(/class="([^"]*)"/) || [, ''])[1];
  const scripts = [...raw.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
  let body = raw.slice(raw.indexOf(bodyTag[0]) + bodyTag[0].length, raw.lastIndexOf('</body>'));
  body = body.replace(/<script>[\s\S]*?<\/script>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  const shell = body.includes('class="shell"');
  if (shell) {
    const a = body.indexOf('<div class="topbar">');
    const b = body.indexOf('</main>') + '</main>'.length;
    body = body.slice(a, b);
  }
  body = body
    .replaceAll('src="../brand/', 'src="/brand/')
    .replace(/href="([a-z-]+)\.html([?#][^"]*)?"/g, (_, n, rest) => `href="/${n}${rest || ''}"`)
    .trim();
  const mod =
    `// generated by scripts/gen-screens.mjs from docs/DESIGN/styled-screens/${f}\n` +
    `export const shell = ${shell};\n` +
    `export const bodyClass = ${JSON.stringify(bodyClass)};\n` +
    `export const script = ${JSON.stringify(scripts.join('\n'))};\n` +
    `export const html = ${JSON.stringify(body)};\n`;
  writeFileSync(join(out, name + '.ts'), mod);
  names.push(name);
}
names.sort();
{
  const d = readFileSync(join(src, 'dashboard.html'), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  let aside = d.slice(d.indexOf('<aside'), d.indexOf('</aside>') + 8);
  aside = aside
    .replace(' active', '')
    .replace(' aria-current="page"', '')
    .replaceAll('src="../brand/', 'src="/brand/')
    .replace(/href="([a-z-]+)\.html"/g, (_, n) => `href="/${n}"`);
  writeFileSync(join(out, 'sidebar.ts'), `// generated by scripts/gen-screens.mjs from dashboard.html\nexport const sidebar = ${JSON.stringify(aside)};\n`);
}
writeFileSync(
  join(out, 'index.ts'),
  `// generated by scripts/gen-screens.mjs\n` +
    names.map((n) => `import * as ${n.replace(/-/g, '_')} from './${n}';`).join('\n') +
    `\nexport const screens = { ${names.map((n) => `'${n}': ${n.replace(/-/g, '_')}`).join(', ')} };\n`
);
console.log('generated', names.length, 'screens');
