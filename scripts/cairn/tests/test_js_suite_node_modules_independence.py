"""POLY-8: `node --test scripts/cairn/tests/js/**/*.test.js` must pass on
a clone/worktree with no `scripts/cairn/dashboard/node_modules` installed.

Found at POLY-4's finish gate (2026-09-23): `token-chart-logic.test.js`
carries two tests that read real files under `scripts/cairn/dashboard/
node_modules/layerchart/` (a version-pin check and a three-way marks-body
diff against the vendored library) -- both throw ENOENT, not a clean
assertion failure, whenever the dashboard hasn't been `npm install`ed.
The finish-feature gate runs the whole JS suite as a HARD GATE (SKILL.md
step 2), so this reproducibly fails the gate in every worktree/clone that
never ran `npm install` under `scripts/cairn/dashboard/` -- identical on
`main`, 479/481 pass.

Ruled fix (matching the precedent `SkillMdPinsTheSvelteCheckGateTests`
already set for the analogous svelte-check gate, test_svelte_check_gate.py):
skip ONLY the two node_modules-dependent tests, with a loud, named reason,
when `dashboard/node_modules/layerchart` is absent -- not the whole file,
and not the whole gate (every other assertion in this file needs no
install and must keep running everywhere).

Real subprocess (`node --test`), never mocked -- the thing under test is
the actual exit code node's test runner returns."""
from __future__ import annotations

import re
import subprocess
import unittest

import helpers  # noqa: F401

REPO_ROOT = helpers.CAIRN_DIR.parent.parent  # scripts/cairn -> scripts -> repo root
JS_TESTS_DIR = helpers.TESTS_DIR / "js"
TOKEN_CHART_LOGIC_TEST_JS = JS_TESTS_DIR / "token-chart-logic.test.js"
LAYERCHART_DIR = helpers.CAIRN_DIR / "dashboard" / "node_modules" / "layerchart"

_SUMMARY_LINE_RE = re.compile(r"^ℹ (pass|fail|tests|skipped) (\d+)\s*$", re.MULTILINE)


def _run_node_test(*paths) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["node", "--test", *[str(p) for p in paths]],
        cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=60,
    )


def _summary(output: str) -> dict:
    return {name: int(count) for name, count in _SUMMARY_LINE_RE.findall(output)}


class TokenChartLogicSuiteNeverThrowsEnoentTests(unittest.TestCase):
    """The specific regression: two tests that read
    dashboard/node_modules/layerchart files directly, uncaught, must never
    surface as an ENOENT stack trace -- a missing local install is an
    expected, named condition, not a crash."""

    def test_token_chart_logic_suite_exits_0_regardless_of_layerchart_presence(self):
        result = _run_node_test(TOKEN_CHART_LOGIC_TEST_JS)
        output = result.stdout + result.stderr
        self.assertEqual(
            result.returncode, 0,
            f"token-chart-logic.test.js must exit 0 whether or not "
            f"{LAYERCHART_DIR} is installed -- {output}",
        )
        self.assertNotIn("ENOENT", output, f"a missing dashboard/node_modules install must skip loudly, "
                          f"not throw an uncaught ENOENT -- {output}")

    def test_layerchart_dependent_tests_skip_with_a_named_reason_when_absent(self):
        if LAYERCHART_DIR.is_dir():
            self.skipTest(f"{LAYERCHART_DIR} is present in this checkout -- nothing to skip, covered by the exit-0 test above")
        result = _run_node_test(TOKEN_CHART_LOGIC_TEST_JS)
        output = result.stdout + result.stderr
        self.assertRegex(
            output, r"layerchart[^\n]*(?:absent|not installed|no such)",
            f"expected a named skip reason mentioning layerchart's absence -- {output}",
        )
        summary = _summary(output)
        self.assertGreaterEqual(summary.get("skipped", 0), 2, f"expected the two layerchart-dependent tests to report skipped -- {output}")


class FullJsSuiteExitsCleanOnAClonelWithNoDashboardNodeModulesTests(unittest.TestCase):
    """POLY-8's acceptance criterion, verbatim: the full glob the
    finish-feature gate runs must pass on a clone/worktree with no
    dashboard/node_modules -- this worktree already has none."""

    def test_full_js_suite_exits_0(self):
        if LAYERCHART_DIR.is_dir():
            self.skipTest(f"{LAYERCHART_DIR} is present in this checkout -- POLY-8's scenario (absent) isn't exercised here")
        js_files = sorted(JS_TESTS_DIR.glob("*.test.js"))
        self.assertTrue(js_files, f"no *.test.js files found under {JS_TESTS_DIR}")
        result = _run_node_test(*js_files)
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 0, f"the full JS suite must exit 0 with no dashboard/node_modules installed -- {output}")


if __name__ == "__main__":
    unittest.main()
